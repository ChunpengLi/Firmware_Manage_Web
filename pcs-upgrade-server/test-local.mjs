import assert from 'node:assert/strict';
import { zipSync } from 'fflate';
import { createHash } from 'node:crypto';
const base = process.env.PCS_TEST_URL || 'http://127.0.0.1:8787';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('This test may only modify local development data');
let cookie = '';
const call = (path, options = {}) => fetch(base + path, { ...options, headers: { ...(cookie ? { cookie } : {}), ...options.headers }, redirect: 'manual' });
assert.equal((await call('/api/admin/manifest')).status, 401);
assert.equal((await call('/registry/index.html')).status, 302);
assert.equal((await call('/api/admin/registry')).status, 401);
assert.equal((await call('/styles.css')).status, 404);
let response = await call('/api/admin/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: 'HS', password: 'wrong-password' }) });
assert.equal(response.status, 401);
response = await call('/api/admin/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: 'HS', password: 'pcs-local-test' }) });
assert.equal(response.status, 200, await response.clone().text());
cookie = response.headers.get('set-cookie').split(';')[0];
assert.equal((await call('/api/admin/session')).status, 200);
const data = Buffer.from(zipSync({ 'test.bin': new Uint8Array(9 * 1024 ** 2) }, { level: 0 }));
const fileName = 'pcs-integration-test-' + Date.now() + '.zip';
response = await call('/api/admin/software', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ version: '4.0.0.0', fileName, fileSize: data.length }) });
assert.equal(response.status, 200, await response.clone().text());
const started = await response.json();
for (let offset = 0, i = 1; offset < data.length; offset += started.chunkSize, i++) {
  response = await call(`/api/admin/uploads/${started.uploadId}/parts/${i}`, { method: 'PUT', body: data.subarray(offset, offset + started.chunkSize) });
  assert.equal(response.status, 200, await response.clone().text());
}
response = await call(`/api/admin/uploads/${started.uploadId}/complete`, { method: 'POST' });
assert.equal(response.status, 200, await response.clone().text());
const result = await response.json();
const md5 = createHash('md5').update(data).digest('hex');
assert.equal(result.md5, md5);
const duplicate = await call('/api/admin/software', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ version: '4.0.0.0', fileName, fileSize: data.length }) });
assert.equal(duplicate.status, 409);
cookie = '';
const versions = await (await call('/api/software/versions')).json();
assert.equal(versions[0].md5, md5);
assert.equal((await (await call('/api/software/latest')).json()).fileName, fileName);
response = await call(versions[0].url);
assert.equal(response.status, 200);
assert.equal(createHash('md5').update(Buffer.from(await response.arrayBuffer())).digest('hex'), md5);
response = await call(versions[0].url, { headers: { range: 'bytes=0-99' } });
assert.equal(response.status, 206);
assert.equal((await response.arrayBuffer()).byteLength, 100);
response = await call('/api/admin/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: 'HS', password: 'pcs-local-test' }) });
cookie = response.headers.get('set-cookie').split(';')[0];
assert.equal((await call('/api/admin/software/' + fileName, { method: 'DELETE' })).status, 200);
assert.equal((await call('/api/admin/logout', { method: 'POST' })).status, 200);
assert.equal((await call('/api/admin/session')).status, 401);
console.log('PASS: HS login/logout, authorization, multipart upload, MD5, duplicate names, version APIs, public download, range download and delete');
